import random  # модуль для генерации случайных чисел

list = [random.randint(-55, 50) for i in range(25)]  # создаём список из 25 случайных чисел от -55 до 50
plus = 0  # счётчик положительных чисел
minus = 0  # счётчик отрицательных чисел
nul = 0  # счётчик нулевых чисел

for char in list:  # перебираем все числа в списке
    if char > 0:  # проверяем положительное число
        plus += 1  # увеличиваем счётчик положительных
    if char < 0:  # проверяем отрицательное число
        minus += 1  # увеличиваем счётчик отрицательных
    if char == 0:  # проверяем ноль
        nul += 1  # увеличиваем счётчик нулевых

percent_plus = plus / 25 * 100  # процент положительных чисел
percent_minus = minus / 25 * 100  # процент отрицательных чисел
percent_nul = nul / 25 * 100  # процент нулевых чисел

biggest = 0  # переменная для хранения максимального числа
smallest = 0  # переменная для хранения минимального числа

for char in list:  # снова перебираем все числа
    if char > biggest:  # если число больше текущего максимума
        biggest = char  # обновляем максимум
    if char < smallest:  # если число меньше текущего минимума
        smallest = char  # обновляем минимум

print(list)  # выводим весь список
print("Процент положительных чисел:", percent_plus, "%")  # выводим процент положительных
print("Процент отрицательных чисел:", percent_minus, "%")  # выводим процент отрицательных
print("Процент нулевых чисел:", percent_nul, "%")  # выводим процент нулевых
print("Наибольшее число:", biggest)  # выводим максимум
print("Наименьшее число:", smallest)  # выводим минимум
